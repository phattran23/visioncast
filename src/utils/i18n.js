// Subtitle language for the player: English or Vietnamese only. Follows the
// interface language unless the user picked one in Settings.
export const SUBTITLE_LANGS = ["en", "vi"];
export function getSubtitleLang() {
  const s = storage.get(STORAGE_KEYS.SUBTITLE_LANG);
  return SUBTITLE_LANGS.includes(s) ? s : getLang();
}

export function getLang() {
  const tmdb = storage.get(STORAGE_KEYS.TMDB_LANG) || "en-US";
  return tmdb.startsWith("vi") ? "vi" : "en";
}

